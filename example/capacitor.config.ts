import type { CapacitorConfig } from '@capacitor/cli'

/**
 * Capacitor configuration. Read by the `cap` CLI (`cap add`, `cap sync`,
 * `cap run`) when it generates and updates the native iOS/Android projects.
 *
 * `cap add ios` / `cap add android` create the native projects. Run
 * `npm run sync` after each change to web code so the native apps pick it up.
 */
const config: CapacitorConfig = {
  /**
   * Reverse-DNS identifier for the app. Used as the bundle id on iOS and the
   * application id on Android. Change it to your own before shipping.
   */
  appId: 'io.event1.terminalexample',

  appName: 'Terminal Example',

  /**
   * The folder containing the built web app. Vite writes to `dist/`.
   */
  webDir: 'dist',

  server: {
    /**
     * Allow plain-HTTP requests to a backend on your dev machine
     * (e.g. http://192.168.1.20:4242). Without this, Android blocks cleartext
     * traffic. REMOVE THIS for production builds and serve your backend over
     * HTTPS.
     */
    cleartext: true,
  },

  plugins: {
    /**
     * Route `fetch()` through the native HTTP stack. The app's WebView origin
     * is `https://localhost`, so calling an `http://` dev backend would
     * otherwise be blocked as mixed content (and need CORS). Native HTTP
     * avoids both. In production you'd call an HTTPS API and could drop this.
     */
    CapacitorHttp: { enabled: true },

    /**
     * Keep the native splash screen (generated by `@capacitor/assets` from
     * assets/splash.png) visible until the app calls `SplashScreen.hide()`
     * in src/main.tsx. Without this the splash disappears as soon as the
     * WebView starts, leaving a blank screen while the JS bundle loads.
     */
    SplashScreen: {
      launchAutoHide: false,
      backgroundColor: '#635bff',
    },
  },
}

export default config
